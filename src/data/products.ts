/**
 * Карта id категории → slug.
 * `category` в коллекции — relationship; при depth:0 Payload возвращает
 * числовой id, а витрина работает со слагами («crossbody», «tote»…).
 */
async function getCategorySlugMap(): Promise<Record<string, string>> {
  const payload = await getPayloadInstance();
  const res = await payload.find({
    collection: "categories",
    limit: 200,
    depth: 0,
  });
  const map: Record<string, string> = {};
  for (const c of res.docs) {
    map[String(c.id)] = String(c.slug);
  }
  return map;
}

function mapPayloadProduct(
  p: RawProduct,
  catMap?: Record<string, string>,
): Product {
  const wbArt = p.wbArticle ? Number(p.wbArticle) : null;
  const ozonArt = p.ozonArticle ? Number(p.ozonArticle) : null;

  const marketplaces: MarketplaceLink[] = [];
  if (wbArt) {
    marketplaces.push({
      name: "Wildberries",
      url: MARKETPLACE_URLS.wbProduct(wbArt),
      icon: "/images/icons/wb.svg",
    });
  }
  if (ozonArt) {
    marketplaces.push({
      name: "Ozon",
      url: MARKETPLACE_URLS.ozonProduct(ozonArt),
      icon: "/images/icons/ozon.svg",
    });
  }

  const gallery = (p.gallery as unknown[]) || [];
  const galleryImages: string[] = gallery
    .map((g: unknown) => (g as { image?: unknown })?.image)
    .filter((x: unknown): x is string => typeof x === "string" && x.length > 0);

  const image = typeof p.image === "string" && p.image ? p.image : galleryImages[0] || "";
  const images = galleryImages.length ? galleryImages : image ? [image] : [];

  const rawChars = (p.characteristics as unknown[]) || [];
  const characteristics: CharacteristicGroup[] = rawChars.map((c: unknown) => {
    const cc = c as { key?: unknown; value?: unknown };
    const key = String(cc.key ?? "");
    return { group_name: key, options: [{ name: key, value: String(cc.value ?? "") }] };
  });

  const modelRaw = p.model;
  const modelId =
    typeof modelRaw === "string"
      ? modelRaw
      : (modelRaw as { id?: string } | null)?.id ?? undefined;

  // category: relationship (число при depth:0) | объект (depth:1) | slug-строка (fallback JSON)
  let categorySlug = "";
  const cat = p.category;
  if (typeof cat === "number") {
    categorySlug = catMap?.[String(cat)] ?? "";
  } else if (cat && typeof cat === "object") {
    categorySlug = String((cat as { slug?: unknown }).slug ?? "");
  } else if (typeof cat === "string") {
    categorySlug = cat;
  }

  return {
    id: String(p.id),
    slug: p.slug,
    sku: p.sku as string | undefined,
    name: p.name as string,
    price: typeof p.price === "number" ? p.price : 0,
    originalPrice: typeof p.originalPrice === "number" ? p.originalPrice : 0,
    wbPrice: typeof p.wbPrice === "number" ? p.wbPrice : undefined,
    wbOriginalPrice:
      typeof p.wbOriginalPrice === "number" ? p.wbOriginalPrice : undefined,
    wbStock: typeof p.wbStock === "number" ? p.wbStock : undefined,
    ozonPrice: typeof p.ozonPrice === "number" ? p.ozonPrice : undefined,
    ozonOriginalPrice:
      typeof p.ozonOriginalPrice === "number" ? p.ozonOriginalPrice : undefined,
    ozonStock: typeof p.ozonStock === "number" ? p.ozonStock : undefined,
    currency: (p.currency as string) || "₽",
    category: categorySlug,
    description: richTextToText(p.description as Parameters<typeof richTextToText>[0]),
    image,
    images,
    video: undefined,
    marketplaces,
    wbArticle: wbArt ?? 0,
    ozonArticle: ozonArt ?? undefined,
    rating: typeof p.rating === "number" ? p.rating : undefined,
    reviewsCount: typeof p.reviewsCount === "number" ? p.reviewsCount : undefined,
    salesCount: undefined,
    colorName: p.colorName as string | undefined,
    composition: p.composition as string | undefined,
    nameAutoGenerated: p.nameAutoGenerated as boolean | undefined,
    descAutoGenerated: p.descAutoGenerated as boolean | undefined,
    archivedAt: p.archivedAt as string | undefined,
    updatedAt: p.updatedAt as string | undefined,
    inStock: (p.inStock as boolean) ?? true,
    isDirectSale: (p.isDirectSale as boolean) ?? false,
    directPrice: typeof p.directPrice === "number" ? p.directPrice : undefined,
    stockQuantity: typeof p.stockQuantity === "number" ? p.stockQuantity : undefined,
    wbCreatedAt: p.wbCreatedAt as string | undefined,
    characteristics: characteristics.length ? characteristics : undefined,
    photoCount: images.length || 1,
    modelId,
  };
}

export async function getProducts(): Promise<Product[]> {
  return cacheGet(
    "all-products",
    async () => {
      try {
        const payload = await getPayloadInstance();
        const catMap = await getCategorySlugMap();
        const res = await payload.find({
          collection: "products",
          where: { inStock: { equals: true } },
          sort: "createdAt",
          limit: 1000,
          depth: 0,
        });
        return res.docs.map((p) => mapPayloadProduct(p as unknown as RawProduct, catMap));
      } catch (err) {
        logger.warn("Payload unavailable, fallback to products.json", {
          error: (err as Error)?.message,
        });
        const fallback = loadJsonFallback<{ products: Product[] }>(
          "products.json",
        );
        if (!fallback?.products) throw err;
        return fallback.products;
      }
    },
    60_000,
    600_000,
  );
}

