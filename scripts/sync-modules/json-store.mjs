/**
 * json-store.mjs — Prisma-подобное хранилище поверх data/products.json.
 *
 * Используется sync-all.mjs, когда PostgreSQL недоступна (JSON fallback):
 * синк читает/обновляет товары из JSON-файла и в конце перезаписывает его
 * в формате, который ожидает src/data/products.ts (см. backup-fallback.mjs).
 *
 * Поддерживается только подмножество Prisma API, которое реально нужно синку:
 *   product.findMany / findFirst / findUnique / create / update
 *   syncRun.create (no-op), $executeRawUnsafe / $queryRawUnsafe / $disconnect
 */

import { existsSync, readFileSync, writeFileSync } from "fs";
import path from "path";

const DEFAULT_CATEGORIES = {
  crossbody: { name: "Кросс-боди", description: "Сумки через плечо" },
  "na-plecho": { name: "На плечо", description: "Сумки на плечо" },
  baguette: { name: "Багет", description: "Сумки-багет" },
  tote: { name: "Тоут", description: "Шоперы и тоуты" },
  saddle: { name: "Седло", description: "Сумки-седло" },
  backpack: { name: "Рюкзак", description: "Рюкзаки" },
};

function clone(v) {
  if (v == null) return v;
  return JSON.parse(
    JSON.stringify(v, (_k, val) => (typeof val === "bigint" ? Number(val) : val))
  );
}

/** Приводит значение к виду, который безопасно лежит в JSON. */
function normVal(v) {
  if (typeof v === "bigint") return Number(v);
  if (v instanceof Date) return v.toISOString();
  return v;
}

/** Приводит «сырую» запись товара (БД или JSON) к полному набору полей. */
function normRecord(p) {
  return {
    id: p.id,
    slug: p.slug,
    sku: p.sku ?? null,
    name: p.name ?? "",
    price: p.price ?? 0,
    originalPrice: p.originalPrice ?? 0,
    currency: p.currency ?? "₽",
    category: p.category ?? "crossbody",
    description: p.description ?? "",
    image: p.image ?? "",
    images: Array.isArray(p.images) ? p.images : [],
    ozonImage: p.ozonImage ?? null,
    ozonImages: Array.isArray(p.ozonImages) ? p.ozonImages : [],
    video: p.video ?? null,
    marketplaces: Array.isArray(p.marketplaces) ? p.marketplaces : [],
    wbArticle: p.wbArticle ?? null,
    ozonArticle: p.ozonArticle ?? null,
    wbPrice: p.wbPrice ?? null,
    wbOriginalPrice: p.wbOriginalPrice ?? null,
    ozonPrice: p.ozonPrice ?? null,
    ozonOriginalPrice: p.ozonOriginalPrice ?? null,
    ozonRating: p.ozonRating ?? null,
    ozonReviewsCount: p.ozonReviewsCount ?? null,
    rating: p.rating ?? null,
    reviewsCount: p.reviewsCount ?? null,
    salesCount: p.salesCount ?? null,
    wbStock: p.wbStock ?? null,
    ozonStock: p.ozonStock ?? null,
    colorName: p.colorName ?? null,
    composition: p.composition ?? null,
    nameAutoGenerated: p.nameAutoGenerated ?? false,
    descAutoGenerated: p.descAutoGenerated ?? false,
    archivedAt: p.archivedAt ?? null,
    inStock: p.inStock ?? true,
    characteristics: p.characteristics ?? null,
    photoCount: p.photoCount ?? 1,
    wbCreatedAt: p.wbCreatedAt ?? null,
    wbUpdatedAt: p.wbUpdatedAt ?? null,
    modelId: p.modelId ?? null,
  };
}

function eq(a, b) {
  return normVal(a) === normVal(b);
}

function matches(rec, where) {
  if (!where) return true;
  for (const [key, cond] of Object.entries(where)) {
    const val = rec[key];
    if (cond && typeof cond === "object" && !Array.isArray(cond) && !(cond instanceof Date)) {
      if ("in" in cond && !cond.in.some((x) => eq(val, x))) return false;
      if ("notIn" in cond && cond.notIn.some((x) => eq(val, x))) return false;
      if ("not" in cond && eq(val, cond.not)) return false;
      if ("gt" in cond && !(val > cond.gt)) return false;
      if ("gte" in cond && !(val >= cond.gte)) return false;
      if ("lt" in cond && !(val < cond.lt)) return false;
      if ("lte" in cond && !(val <= cond.lte)) return false;
      if ("equals" in cond && !eq(val, cond.equals)) return false;
    } else if (!eq(val, cond)) {
      return false;
    }
  }
  return true;
}

function pick(rec, select) {
  if (!select) return clone(rec);
  const out = {};
  for (const [key, enabled] of Object.entries(select)) {
    if (enabled) out[key] = clone(rec[key]);
  }
  return out;
}

function compareIds(a, b) {
  const na = parseInt(String(a).replace(/\D+/g, ""), 10);
  const nb = parseInt(String(b).replace(/\D+/g, ""), 10);
  if (Number.isFinite(na) && Number.isFinite(nb) && na !== nb) return na - nb;
  return String(a).localeCompare(String(b));
}

/**
 * Маппинг записи в формат приложения (data/products.json).
 * Полностью повторяет scripts/backup-fallback.mjs, чтобы файл не «прыгал»
 * между экспортом из БД и JSON-режимом синка.
 */
function toAppProduct(p) {
  return {
    id: p.id,
    slug: p.slug,
    sku: p.sku || undefined,
    name: p.name,
    price: p.price,
    originalPrice: p.originalPrice,
    wbPrice: p.wbPrice || undefined,
    wbOriginalPrice: p.wbOriginalPrice || undefined,
    ozonPrice: p.ozonPrice || undefined,
    ozonOriginalPrice: p.ozonOriginalPrice || undefined,
    currency: p.currency,
    category: p.category,
    description: p.description,
    image: p.image || "",
    images: p.images || [],
    marketplaces: (() => {
      const mps = Array.isArray(p.marketplaces) ? p.marketplaces : [];
      const result = [];
      const wbArt = p.wbArticle ? Number(p.wbArticle) : null;
      const ozonArt = p.ozonArticle ? Number(p.ozonArticle) : null;
      if (wbArt && !mps.some((m) => m.name === "Wildberries")) {
        result.push({
          name: "Wildberries",
          url: `https://www.wildberries.ru/catalog/${wbArt}/detail.aspx`,
          icon: "/images/icons/wb.svg",
        });
      }
      if (ozonArt && !mps.some((m) => m.name === "Ozon")) {
        result.push({
          name: "Ozon",
          url: `https://www.ozon.ru/product/${ozonArt}/`,
          icon: "/images/icons/ozon.svg",
        });
      }
      for (const mp of mps) {
        if (!result.some((m) => m.name === mp.name)) result.push(mp);
      }
      return result;
    })(),
    wbArticle: p.wbArticle ? Number(p.wbArticle) : 0,
    ozonArticle: p.ozonArticle ? Number(p.ozonArticle) : undefined,
    rating: p.rating || undefined,
    reviewsCount: p.reviewsCount || undefined,
    salesCount: p.salesCount || undefined,
    colorName: p.colorName || undefined,
    composition: p.composition || undefined,
    nameAutoGenerated: p.nameAutoGenerated || undefined,
    descAutoGenerated: p.descAutoGenerated || undefined,
    archivedAt: p.archivedAt || undefined,
    inStock: p.inStock,
    wbCreatedAt: p.wbCreatedAt || undefined,
    characteristics: p.characteristics || undefined,
    photoCount: p.photoCount || 1,
    modelId: p.modelId || undefined,
  };
}

/**
 * Создаёт JSON-хранилище.
 * @param {{ file?: string, log?: { line?: Function } }} [opts]
 */
export function createJsonStore({
  file = path.join(process.cwd(), "data", "products.json"),
  log = null,
} = {}) {
  const abs = path.resolve(file);
  if (!existsSync(abs)) {
    throw new Error(`JSON fallback не найден: ${abs}`);
  }

  const raw = JSON.parse(readFileSync(abs, "utf8"));
  if (!Array.isArray(raw.products)) {
    throw new Error(`JSON fallback повреждён (нет products[]): ${abs}`);
  }

  const categories =
    Array.isArray(raw.categories) && raw.categories.length > 0
      ? raw.categories
      : Object.entries(DEFAULT_CATEGORIES).map(([slug, info]) => ({
          slug,
          name: info.name,
          description: info.description,
          image: `/images/categories/${slug}.jpg`,
          count: 0,
        }));
  const settings = raw.settings ?? null;

  /** @type {Map<string, object>} */
  const records = new Map();
  for (const p of raw.products) {
    const rec = normRecord(p);
    records.set(rec.id, rec);
  }

  log?.line?.(`[JSON] ${file}: ${records.size} товаров`);

  const findByField = (field, value) => {
    for (const rec of records.values()) {
      if (eq(rec[field], value)) return rec;
    }
    return null;
  };

  const store = {
    /** Маркер: main() понимает, что работает без БД. */
    __jsonStore: true,
    file: abs,

    product: {
      async findMany(args = {}) {
        let list = [...records.values()].filter((r) => matches(r, args.where));
        const order = args.orderBy && Object.entries(args.orderBy)[0];
        if (order) {
          const [field, dir] = order;
          list.sort((a, b) =>
            field === "id"
              ? compareIds(a.id, b.id)
              : String(a[field] ?? "").localeCompare(String(b[field] ?? ""))
          );
          if (dir === "desc") list.reverse();
        }
        if (args.skip) list = list.slice(args.skip);
        if (args.take) list = list.slice(0, args.take);
        return list.map((r) => pick(r, args.select));
      },

      async findFirst(args = {}) {
        const res = await store.product.findMany({ ...args, take: 1 });
        return res[0] ?? null;
      },

      async findUnique(args = {}) {
        const where = args.where || {};
        let rec = null;
        if (where.id !== undefined) rec = records.get(where.id) || findByField("id", where.id);
        else if (where.slug !== undefined) rec = findByField("slug", where.slug);
        else {
          const [field, value] = Object.entries(where)[0] || [];
          if (field) rec = findByField(field, value);
        }
        return rec ? pick(rec, args.select) : null;
      },

      async create({ data }) {
        const rec = normRecord({
          ...Object.fromEntries(
            Object.entries(data || {}).map(([k, v]) => [k, normVal(v)])
          ),
        });
        if (!rec.id) throw new Error("JSON store: product.create без id");
        if (!rec.slug) rec.slug = rec.id;
        if (records.has(rec.id)) {
          const err = new Error(`JSON store: товар ${rec.id} уже существует`);
          err.code = "P2002";
          throw err;
        }
        if (findByField("slug", rec.slug)) {
          const err = new Error(`JSON store: slug ${rec.slug} уже занят`);
          err.code = "P2002";
          throw err;
        }
        if (rec.sku && findByField("sku", rec.sku)) {
          const err = new Error(`JSON store: sku ${rec.sku} уже занят`);
          err.code = "P2002";
          throw err;
        }
        if (rec.wbArticle != null && findByField("wbArticle", rec.wbArticle)) {
          const err = new Error(`JSON store: wbArticle ${rec.wbArticle} уже занят`);
          err.code = "P2002";
          throw err;
        }
        if (rec.ozonArticle != null && findByField("ozonArticle", rec.ozonArticle)) {
          const err = new Error(`JSON store: ozonArticle ${rec.ozonArticle} уже занят`);
          err.code = "P2002";
          throw err;
        }
        records.set(rec.id, rec);
        return clone(rec);
      },

      async update({ where, data }) {
        const rec = records.get(where?.id) || findByField("id", where?.id);
        if (!rec) {
          const err = new Error(`JSON store: товар ${where?.id} не найден`);
          err.code = "P2025";
          throw err;
        }
        for (const [key, value] of Object.entries(data || {})) {
          if (value === undefined) continue;
          rec[key] = normVal(value);
        }
        return clone(rec);
      },

      async count(args = {}) {
        return [...records.values()].filter((r) => matches(r, args.where)).length;
      },
    },

    // История синка в JSON-режиме не нужна (SyncRun — таблица БД).
    syncRun: {
      async create() {
        return {};
      },
    },

    async $executeRawUnsafe() {
      return 0;
    },

    async $queryRawUnsafe() {
      return [{ "?column?": 1 }];
    },

    async $disconnect() {},

    /** Записывает data/products.json в формате приложения. */
    save() {
      const all = [...records.values()].sort((a, b) => compareIds(a.id, b.id));
      // Как backup-fallback.mjs: только то, что показывается в каталоге.
      const visible = all.filter((p) => !p.archivedAt && p.inStock && p.price > 0);
      const products = visible.map(toAppProduct);

      const counts = {};
      for (const p of visible) counts[p.category] = (counts[p.category] || 0) + 1;
      const outCategories = categories.map((c) => ({
        ...c,
        count: counts[c.slug] || 0,
      }));

      const output = { products, categories: outCategories, settings };
      const json = JSON.stringify(
        output,
        (_k, v) => (typeof v === "bigint" ? Number(v) : v),
        2
      );
      writeFileSync(abs, json);

      return {
        count: products.length,
        sizeKB: (Buffer.byteLength(json) / 1024).toFixed(1),
      };
    },
  };

  return store;
}
